/**
 * nav-icons.ts — write the admin sidebar icons into src/app/(payload)/custom.scss.
 *
 *   pnpm nav-icons            rewrite the block
 *   pnpm nav-icons --check    exit 1 if the block is out of date (tests/fitness/nav-icons.test.ts)
 *
 * Each admin nav entry has an id (`nav-<collection slug>`, `nav-global-<slug>`,
 * or a custom link's own id); custom.scss masks its `::before` with
 * `--msb-icon`; the closed-sidebar rail (NavRail.tsx) uses the same ids as
 * `data-nav-icon`. This turns the table below into those rules, from the Font
 * Awesome free-solid icons the site already uses. To give a new entry an icon,
 * add a line here and run the script.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import type { IconDefinition } from '@fortawesome/fontawesome-svg-core'
import {
  faBoxArchive,
  faCalendarDays,
  faChartColumn,
  faFileLines,
  faFolder,
  faHouse,
  faImage,
  faKey,
  faPenNib,
  faRightFromBracket,
  faScrewdriverWrench,
  faSliders,
  faTableColumns,
  faUserShield,
  faUsers,
  faWandMagicSparkles,
} from '@fortawesome/free-solid-svg-icons'

export const NAV_ICONS: [id: string, icon: IconDefinition, name: string, alsoFor?: string][] = [
  ['nav-start', faTableColumns, 'faTableColumns'],
  // the rail's "Browse by Folder" (the sidebar button keeps Payload's own folder icon)
  ['nav-folders', faFolder, 'faFolder'],
  ['nav-blog', faPenNib, 'faPenNib'],
  ['nav-events', faCalendarDays, 'faCalendarDays'],
  ['nav-pages', faFileLines, 'faFileLines'],
  ['nav-workshops', faScrewdriverWrench, 'faScrewdriverWrench'],
  ['nav-media', faImage, 'faImage'],
  ['nav-global-heroSettings', faHouse, 'faHouse'],
  ['nav-global-siteSettings', faSliders, 'faSliders'],
  ['nav-users', faUsers, 'faUsers'],
  ['nav-roles', faUserShield, 'faUserShield'],
  ['nav-permissions', faKey, 'faKey'],
  // Verwaltung → KI-Zugänge: the MCP plugin's API keys (Claude in the CMS).
  ['nav-payload-mcp-api-keys', faWandMagicSparkles, 'faWandMagicSparkles'],
  // Backups view (E8), link from src/plugins/backups/components/BackupsNavLink.tsx.
  // S5.11: site statistics, for every CMS user
  ['nav-statistik', faChartColumn, 'faChartColumn'],
  ['nav-backups', faBoxArchive, 'faBoxArchive'],
  // logout: the rail's button (S9.6) and Payload's own button in the open sidebar
  ['nav-logout', faRightFromBracket, 'faRightFromBracket', '.nav__log-out'],
]

const HEADER = '// ── Nav icons (Font Awesome 7 free-solid; generated, one per entry id) ─────'
const NOTE = '// Generated by scripts/nav-icons.ts (pnpm nav-icons); edit the table there, not here.'
const FILE = path.resolve(import.meta.dirname, '../src/app/(payload)/custom.scss')

const svg = ({ icon: [width, height, , , d] }: IconDefinition) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}"><path d="${Array.isArray(d) ? d.join(' ') : d}"/></svg>`

export function renderBlock() {
  const rules = NAV_ICONS.map(
    ([id, icon, name, alsoFor]) =>
      `#${id}, [data-nav-icon='${id}']${alsoFor ? `, ${alsoFor}` : ''} { --msb-icon: url("data:image/svg+xml,${encodeURIComponent(svg(icon))}"); } // ${name}`,
  )
  return [HEADER, NOTE, ...rules].join('\n')
}

/** custom.scss with the icon block (from its header to the end of the file) replaced. */
export function withBlock(scss: string) {
  const at = scss.indexOf(HEADER)
  if (at < 0) throw new Error(`custom.scss has no "${HEADER}" line`)
  return `${scss.slice(0, at)}${renderBlock()}\n`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const current = readFileSync(FILE, 'utf8')
  const next = withBlock(current)
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('custom.scss nav icons are out of date; run pnpm nav-icons')
      process.exit(1)
    }
  } else if (next !== current) {
    writeFileSync(FILE, next)
    console.log(`custom.scss: ${NAV_ICONS.length} nav icons written`)
  } else {
    console.log('custom.scss: nav icons up to date')
  }
}
